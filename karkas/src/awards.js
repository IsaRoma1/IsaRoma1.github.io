/* Награды · этап 1
   ────────────────────────────────────────────────────────────────
   Пять наград поверх процента. Считаются из тех же обязательств, что
   и рейтинг, — своего источника данных у наград нет и быть не должно:
   награда, которую нельзя проверить по цифрам на том же экране, на
   планёрке не защищается.

   Главное правило — КУБКИ РАЗЫГРЫВАЮТСЯ ВНУТРИ ГРУППЫ, мастера
   отдельно от остальных. Иначе соревнования не выходит: у мастеров
   30–70 дел в месяц и 57% в среднем, у остальных 14 дел и 72%.
   В общем зачёте лучший мастер стоит двенадцатым и не выиграет
   никогда — а значит, и играть перестанет.

   Награды следуют за выбранным периодом, а не за календарным месяцем:
   на экране виден один набор чисел, и награда обязана считаться ровно
   по нему. Поэтому в названиях нет слова «месяц».

   Порог тот же, что у рейтинга (LOW_N): у кого мало дел — наград нет.
   Иначе человек с одной закрытой задачей получает кубок, и вся затея
   обесценивается первым же таким случаем. */

(function () {
  "use strict";

  /* Знаки наград.
     ────────────────────────────────────────────────────────────
     Фигуры сплошные, а не контурные: контур в 17 пикселей читается
     как обводка поля ввода, а не как награда. Заливка тут уместна —
     значки стоят у правого края, отдельной колонкой, и со шкалами
     (там заливка означает долю дел) в одну строку взгляда не попадают.

     Номер места внутрь знака не пишем: он уже стоит слева, в колонке
     ранга. Кубок отличается от медали формой, серебро от бронзы —
     цветом, а точное место всегда рядом цифрой. */
  const svg = (inner) =>
    `<svg viewBox="0 0 24 24" aria-hidden="true">${inner}</svg>`;

  /* Кубок: чаша, две ручки, ножка, подставка. */
  const ICON_CUP = svg(
    `<path d="M6 2.8h12v5.1a6 6 0 0 1-12 0V2.8Z"/>` +
    `<path d="M6 4.4H3.4v1.7c0 2 1.4 3.6 3.3 3.9" fill="none" stroke="currentColor" stroke-width="1.7"/>` +
    `<path d="M18 4.4h2.6v1.7c0 2-1.4 3.6-3.3 3.9" fill="none" stroke="currentColor" stroke-width="1.7"/>` +
    `<path d="M10.9 13.6h2.2v3.6h-2.2z"/>` +
    `<path d="M7.2 21.2 8.2 17.4h7.6l1 3.8H7.2Z"/>`);

  /* Медаль: две широкие ленты и сплошной диск с гравированным ободком.
     Диск именно сплошной — прорезанное кольцо на 21 пикселе читается
     замочной скважиной, а не наградой. Ободок рисуем светлой обводкой
     поверх заливки: он даёт объём и не трогает силуэт. */
  const ICON_MEDAL = svg(
    `<path d="M6.6 1.7h4.1l3.1 6-3.6 1.9-3.6-7.9Z" opacity=".55"/>` +
    `<path d="M17.4 1.7h-4.1l-3.1 6 3.6 1.9 3.6-7.9Z" opacity=".55"/>` +
    `<circle cx="12" cy="15.3" r="6.9"/>` +
    `<circle cx="12" cy="15.3" r="3.7" fill="none" stroke="#fff"` +
    ` stroke-opacity=".5" stroke-width="1.5"/>`);

  /* Звезда — «ни одного промаха». */
  const ICON_STAR = svg(
    `<path d="M12 2.2l3 6.1 6.7 1-4.85 4.73 1.15 6.67L12 17.55 6 20.7l1.15-6.67L2.3 9.3l6.7-1 3-6.1Z"/>`);

  /* Штанга — «тяжеловес», награда за объём. */
  const ICON_BAR = svg(
    `<rect x="1.8" y="9.4" width="2.7" height="5.2" rx="1.2"/>` +
    `<rect x="5.1" y="6.6" width="3.4" height="10.8" rx="1.5"/>` +
    `<rect x="15.5" y="6.6" width="3.4" height="10.8" rx="1.5"/>` +
    `<rect x="19.5" y="9.4" width="2.7" height="5.2" rx="1.2"/>` +
    `<rect x="8.5" y="10.7" width="7" height="2.6" rx=".6"/>`);

  /* Описания наград. why(x) — строка «за что», она же показывается в
     карточке человека. Текст всегда с числами: «первое место» без
     «83%, 10 из 12» — повод для спора, а не для награды. */
  const DEFS = {
    place1: {
      icon: ICON_CUP, cls: "gold", title: "Первое место",
      why: (x) => `Лучший результат среди ${x.groupGen} — ${x.pct}%, ${x.ok} из ${x.n}.`,
    },
    place2: {
      icon: ICON_MEDAL, cls: "silver", title: "Второе место",
      why: (x) => `Второй результат среди ${x.groupGen} — ${x.pct}%, ${x.ok} из ${x.n}.`,
    },
    place3: {
      icon: ICON_MEDAL, cls: "bronze", title: "Третье место",
      why: (x) => `Третий результат среди ${x.groupGen} — ${x.pct}%, ${x.ok} из ${x.n}.`,
    },
    clean: {
      icon: ICON_STAR, cls: "clean", title: "Без промахов",
      why: (x) => `Все дела сданы в срок — ${x.ok} из ${x.n}, ни одного пропущенного.`,
    },
    heavy: {
      icon: ICON_BAR, cls: "heavy", title: "Тяжеловес",
      why: (x) => `Больше всех дел среди ${x.groupGen} — ${x.n}, ` +
                  `и это не в ущерб качеству: ${x.pct}% при среднем по группе ${x.groupPct}%.`,
    },
  };

  /* Родительный падеж для «среди …» — чтобы строка «за что» читалась
     по-русски, а не «среди мастера». */
  const GROUP_GEN = { masters: "мастеров", others: "остальных сотрудников" };

  let BY_PERSON = new Map();

  /* groups: [{ id, rows: [{ key, name, ok, n, pct }] }]
     rows приходят уже посчитанными — awards.js не лезет в обязательства
     сам, иначе метрика раздвоится и однажды разойдётся с рейтингом. */
  function compute(groups, lowN) {
    BY_PERSON = new Map();

    for (const g of groups) {
      /* Ранжируем ровно так же, как рисуется рейтинг: процент, потом
         объём, потом имя. Если порядок разойдётся, кубок сядет не на ту
         строку — и это заметят в первую же минуту. */
      const ranked = g.rows
        .filter((r) => r.n >= lowN && r.pct !== null)
        .sort((a, b) => (b.pct - a.pct) || (b.n - a.n) ||
                        String(a.name).localeCompare(String(b.name), "ru"));
      if (!ranked.length) continue;

      const groupGen = GROUP_GEN[g.id] || "коллег";
      /* Средний процент по группе — складываем дела, а не проценты
         (правило 3 из BRIEF): у мастера 40 дел, у сметчика 8, среднее
         двух процентов дало бы им равный вес. */
      const sumOk = ranked.reduce((s, r) => s + r.ok, 0);
      const sumN = ranked.reduce((s, r) => s + r.n, 0);
      const groupPct = sumN ? Math.round((sumOk / sumN) * 100) : 0;

      const give = (r, id, goal) => {
        const x = { ...r, groupGen, groupPct };
        const list = BY_PERSON.get(r.key) || [];
        list.push({ id, ...DEFS[id], text: DEFS[id].why(x), goal: goal || "" });
        BY_PERSON.set(r.key, list);
      };

      /* Насколько отстал от первого места. Раньше здесь стояло «до
         первого места — 4 п.п.», и это оказалось непонятно даже
         заказчику: «процентный пункт» — слово из экономических сводок,
         начальнику участка оно ничего не говорит. Показываем оба числа
         рядом — сравнение видно глазом, объяснять нечего. */
      const first = ranked[0];
      const behind = (r) => (first.pct > r.pct
        ? `Первое место — ${first.pct}%, у вас ${r.pct}%.`
        : "При равном проценте выше тот, у кого больше дел.");

      ranked.forEach((r, i) => {
        if (i === 0) give(r, "place1", "Лучший результат в группе.");
        else if (i === 1) give(r, "place2", behind(r));
        else if (i === 2) give(r, "place3", behind(r));
        if (r.pct === 100) give(r, "clean");
      });

      /* Тяжеловес — награда за объём, и придумана она ради мастеров:
         по проценту они офису проигрывают структурно, а работы тянут
         вдвое больше. Оговорка про средний процент нужна, чтобы кубок
         не достался тому, кто просто набрал много и всё провалил. */
      if (ranked.length >= 3) {
        const maxN = Math.max(...ranked.map((r) => r.n));
        for (const r of ranked) {
          if (r.n === maxN && r.pct >= groupPct) give(r, "heavy");
        }
      }
    }
    return BY_PERSON;
  }

  const forPerson = (key) => BY_PERSON.get(key) || [];

  /* Значки в строке рейтинга. Больше двух не ставим: строка узкая, а
     третий значок превращает рейтинг в ёлку.

     Пояснение вешаем прямо на знак — атрибутами, а не поиском по ключу
     при наведении: разметка сама себя описывает, и подсказка не
     разъедется с наградой после перерисовки.

     Контейнер отдаём всегда, даже пустой: значки стоят отдельной
     колонкой сетки, и без него строки без наград разъехались бы. */
  function badgesHTML(key) {
    const list = forPerson(key);
    if (!list.length) return `<span class="aw-row"></span>`;
    const shown = list.slice(0, 2);
    const rest = list.length - shown.length;
    const one = (a) => `<i class="aw ${a.cls}" tabindex="0" data-t="${
      escAttr(a.title)}" data-w="${escAttr(a.text)}"${
      a.goal ? ` data-g="${escAttr(a.goal)}"` : ""}>${a.icon}</i>`;
    return `<span class="aw-row">${shown.map(one).join("")}${
      rest ? `<i class="aw more" data-t="Ещё награды" data-w="У человека их ${
        list.length}: показаны две, остальные — ${
        escAttr(list.slice(2).map((a) => a.title.toLowerCase()).join(", "))
      }.">+${rest}</i>` : ""}</span>`;
  }

  /* Своя мелкая экранировка: awards.js не должен зависеть от порядка
     подключения скриптов. */
  function escAttr(s) {
    return String(s).replace(/[&<>"']/g, (c) => (
      { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  window.Awards = {
    DEFS, compute, forPerson, badgesHTML,
    /* Для легенды в карточке-справке: список всех наград и условий. */
    legend: () => [
      [ICON_CUP, "gold", "Первое место", "лучший процент в своей группе"],
      [ICON_MEDAL, "silver", "Второе место", "второй процент в группе"],
      [ICON_MEDAL, "bronze", "Третье место", "третий процент в группе"],
      [ICON_STAR, "clean", "Без промахов", "все дела сданы в срок, ни одного пропущенного"],
      [ICON_BAR, "heavy", "Тяжеловес", "больше всех дел в группе при проценте не ниже среднего"],
    ],
  };
})();
